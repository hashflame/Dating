/**
 * Сообщения и суперсообщения.
 *
 * Приложение сообщения **не доставляет**: оно готовит текст и открывает личку
 * Telegram с человеком — дальше пара переписывается там же, где переписывается
 * со всеми остальными. Мы берём плату не за доставку, а за сам переход:
 * 10 переходов к мэтчам в неделю бесплатно, дальше ✦3; к человеку без мэтча —
 * 1 в неделю бесплатно, дальше ✦10.
 *
 * Контракта на бэкенде ещё нет — тип описан по заведённым тикетам,
 * см. `docs/api-gaps.md`. Как появится DTO, сверить и убрать заглушки.
 */

/**
 * Обычное сообщение — мэтчу, суперсообщение — кому угодно из ленты: мэтч ему
 * не нужен, получатель увидит текст в «Симпатиях».
 */
export type MessageKind = 'message' | 'super'

/** Недельный лимит одного вида сообщений и цена сверх него. */
export type MessageAllowance = {
  /** Сколько уже отправлено в текущем окне. */
  used: number
  /** Сколько бесплатных за неделю: 10 обычных, 1 суперсообщение. */
  limit: number
  /** Сколько бесплатных осталось. Сервер считает сам — не выводим из `used`. */
  remaining: number
  /** ISO-8601: когда окно обнулится. */
  resetsAt: string
  /** Цена в зорках за одно сообщение сверх лимита. */
  cost: number
}

export type MessageLimits = {
  message: MessageAllowance
  superMessage: MessageAllowance
  /** Баланс зорок — им оплачиваются сообщения сверх лимита. */
  sparksBalance: number
}

/**
 * Разрешение на переход: сервер списал зорки (или зачёл бесплатный) и отдал,
 * куда вести.
 */
export type ChatHandoff = {
  messageId: string
  kind: MessageKind
  /** 0, если переход уложился в бесплатный лимит. */
  sparksSpent: number
  sparksBalance: number
  /** Лимиты после списания — чтобы не перезапрашивать их отдельным запросом. */
  limits: MessageLimits
  /** Ссылка на личку: `https://t.me/<username>`. */
  chatUrl: string
  telegramUsername: string | null
}

/**
 * Почему перейти нельзя. Коды ошибок сервера — по ним показываем не общее
 * «что-то пошло не так», а что именно случилось с этим человеком.
 */
export type MessageBlockReason =
  /** Человек включил «Запретить писать мне» (T-16.1). */
  | 'blocksMessages'
  /** Аккаунт удалён. */
  | 'deleted'
  /** Блокировка в одну из сторон. */
  | 'blocked'
  /** Юзернейма в Telegram нет — переходить некуда. */
  | 'noUsername'
  /** Не хватает зорок на платный переход. */
  | 'noSparks'
  /** Всё остальное. */
  | 'unknown'

/**
 * Суперсообщение в списке входящих симпатий: его показывают отдельным блоком
 * с текстом, а не бейджем на фото.
 */
export type SuperMessagePreview = {
  text: string
  sentAt: string
}
