/**
 * Сообщения и суперсообщения.
 *
 * Обычное сообщение приложение **не доставляет**: оно готовит текст и открывает
 * личку Telegram с мэтчем — дальше пара переписывается там же, где переписывается
 * со всеми остальными. Плата берётся не за доставку, а за сам переход:
 * 10 переходов к мэтчам в неделю бесплатно, дальше ✦3.
 *
 * Суперсообщение в Telegram не ведёт: мэтча ещё нет, и вываливать человеку
 * личку того, кого он не выбирал, нельзя. Текст остаётся в приложении и ждёт
 * получателя во вкладке «Мэтчи» — 1 суперсообщение в неделю бесплатно,
 * дальше ✦10.
 *
 * Контракта на бэкенде ещё нет — тип описан по заведённым тикетам,
 * см. `docs/api-gaps.md`. Как появится DTO, сверить и убрать заглушки.
 */

/**
 * Обычное сообщение — мэтчу, с переходом в Telegram. Суперсообщение — кому
 * угодно из ленты: мэтча не нужно, перехода нет, получатель читает текст
 * во вкладке «Мэтчи».
 */
export type MessageKind = 'message' | 'super'

/** Недельный лимит одного вида сообщений и цена сверх него. */
export type MessageAllowance = {
  /** Сколько уже отправлено в текущем окне. */
  used: number
  /** Сколько бесплатных за неделю: 10 обычных, 1 суперсообщение. */
  limit: number
  /** Сколько бесплатных осталось. Сервер считает сам — не выводим из `used`. */
  remaining: number
  /** ISO-8601: когда окно обнулится. */
  resetsAt: string
  /** Цена в зорках за одно сообщение сверх лимита. */
  cost: number
}

export type MessageLimits = {
  message: MessageAllowance
  superMessage: MessageAllowance
  /** Баланс зорок — им оплачиваются сообщения сверх лимита. */
  sparksBalance: number
}

/**
 * Сообщение принято: сервер списал зорки (или зачёл бесплатный) и, если это
 * обычное сообщение мэтчу, отдал, куда вести.
 */
export type ChatHandoff = {
  messageId: string
  kind: MessageKind
  /** 0, если переход уложился в бесплатный лимит. */
  sparksSpent: number
  sparksBalance: number
  /** Лимиты после списания — чтобы не перезапрашивать их отдельным запросом. */
  limits: MessageLimits
  /**
   * Ссылка на личку: `https://t.me/<username>`. У суперсообщения — `null`:
   * переходить некуда, текст доставляется внутри приложения.
   */
  chatUrl: string | null
  telegramUsername: string | null
}

/**
 * Почему перейти нельзя. Коды ошибок сервера — по ним показываем не общее
 * «что-то пошло не так», а что именно случилось с этим человеком.
 */
export type MessageBlockReason =
  /** Человек включил «Запретить писать мне» (T-16.1). */
  | 'blocksMessages'
  /** Аккаунт удалён. */
  | 'deleted'
  /** Блокировка в одну из сторон. */
  | 'blocked'
  /** Юзернейма в Telegram нет — переходить некуда. */
  | 'noUsername'
  /** Не хватает зорок на платный переход. */
  | 'noSparks'
  /** Всё остальное. */
  | 'unknown'

/**
 * Полученное суперсообщение: его показывают во вкладке «Мэтчи» отдельной
 * карточкой с текстом, а не бейджем на фото.
 */
export type SuperMessagePreview = {
  text: string
  sentAt: string
}
