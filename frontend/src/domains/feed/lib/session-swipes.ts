/**
 * Сколько карточек человек оценил с момента запуска приложения.
 *
 * Нужен ровно одному событию — `feed_exhausted`: важно не то, что карточки
 * кончились, а то, после скольких свайпов. Один свайп и пустая лента — это
 * плохой подбор, сорок свайпов — нормальный конец сессии.
 *
 * Модульная переменная, а не состояние: счётчик живёт столько же, сколько
 * вкладка, и ни один компонент от него не перерисовывается.
 */
let swipes = 0

export function countSwipe(): void {
  swipes += 1
}

export function swipesInSession(): number {
  return swipes
}
