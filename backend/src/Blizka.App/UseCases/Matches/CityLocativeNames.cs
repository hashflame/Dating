/// ломали согласование при подстановке реального имени города (тикет ClickUp: «по центру Минск» вместо
/// «по центру Минска» получалось бы при простой подстановке <c>City.NameRu</c> как есть). Справочник городов
/// закрытый и небольшой (T-4.1), поэтому формы просто перечислены, а не выводятся алгоритмом склонения.
/// </summary>
