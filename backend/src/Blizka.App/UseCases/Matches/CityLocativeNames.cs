    /// <summary>
    /// Форма города для слота «в {0}» — известный город даёт правильный предложный падеж, неизвестный/отсутствующий
    /// откатывается на <see cref="DateIdeaCatalog.DefaultCityPlaceholder"/> (уже согласован с этой конструкцией).
    /// </summary>
    public static string ForInPhrase(string? cityNameRu) =>
        !string.IsNullOrWhiteSpace(cityNameRu) && Forms.TryGetValue(cityNameRu, out var locative)
            ? locative
            : DateIdeaCatalog.DefaultCityPlaceholder;
}
